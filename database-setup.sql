create or replace function public.checkin_state(p_session_hash text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare actor public.checkin_accounts; result jsonb;
begin
 perform 1 from public.checkin_settings where singleton for share;
 actor:=public.checkin_actor(p_session_hash);
 if actor.role not in ('admin','leader') then raise exception using errcode='42501',message='관리자의 조 배정이 필요합니다.'; end if;
 with visible as (select * from public.checkin_members m where actor.role='admin' or m.group_number=actor.group_number)
 select jsonb_build_object(
 'members',coalesce((select jsonb_agg(jsonb_build_object('id',m.id,'name',m.name,'group',m.group_number,'active',case when m.active then 1 else 0 end) order by m.id) from visible m),'[]'::jsonb),
 'attendance',coalesce((select jsonb_agg(jsonb_build_object('memberId',a.member_id,'date',a.date,'checked',case when a.checked then 1 else 0 end,'updatedBy',a.updated_by) order by a.member_id,a.date) from public.checkin_attendance a join visible m on m.id=a.member_id),'[]'::jsonb),
 'breakWeeks',coalesce((select jsonb_agg(jsonb_build_object('week',b.week,'reason',b.reason) order by b.week desc) from public.checkin_break_weeks b),'[]'::jsonb),
 'breakDays',coalesce((select jsonb_agg(jsonb_build_object('date',b.date,'reason',b.reason) order by b.date desc) from public.checkin_break_days b),'[]'::jsonb),
 'order',coalesce((select jsonb_agg(x.id order by x.position) from public.checkin_orders o cross join lateral unnest(o.member_ids) with ordinality x(id,position) join visible m on m.id=x.id where o.user_id=actor.id),'[]'::jsonb),
 'user',jsonb_build_object('id',actor.id,'name',actor.name,'role',actor.role,'group',actor.group_number),
 'users',case when actor.role='admin' then coalesce((select jsonb_agg(jsonb_build_object('id',a.id,'name',a.name,'role',a.role,'group',a.group_number) order by a.id) from public.checkin_accounts a),'[]'::jsonb) else '[]'::jsonb end,
 'teamName',(select team_name from public.checkin_settings where singleton),
 'revision',(select revision from public.checkin_settings where singleton),
 'today',(now() at time zone 'Asia/Seoul')::date,
 'week',(now() at time zone 'Asia/Seoul')::date-extract(dow from (now() at time zone 'Asia/Seoul')::date)::int,
 'legacyCount',0
 ) into result;
 return result;
end $$;
