create or replace function public.checkin_actor(p_session_hash text)
returns public.checkin_accounts language plpgsql security definer set search_path='' as $$
declare actor public.checkin_accounts;
begin
 select a.* into actor from public.checkin_sessions s join public.checkin_accounts a on a.id=s.user_id
 where s.token_hash=p_session_hash and s.expires_at>now();
 if not found then raise exception using errcode='28000',message='로그인이 필요합니다.'; end if;
 return actor;
end $$;

-- Call ONLY after a trusted server has exchanged and verified the Toss authorization code.
create or replace function public.checkin_open_session(p_user_key text,p_name text,p_token_hash text,p_admin_user_key text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare actor public.checkin_accounts;
begin
 if coalesce(length(btrim(p_admin_user_key)),0)=0 then raise exception '관리자 토스 사용자 키 설정이 필요합니다.'; end if;
 perform 1 from public.checkin_settings where singleton for update;
 insert into public.checkin_accounts(id,name,role) values(p_user_key,btrim(p_name),case when p_user_key=p_admin_user_key then 'admin' else 'pending' end)
 on conflict(id) do update set name=excluded.name;
 if p_user_key=p_admin_user_key then update public.checkin_accounts set role='admin',group_number=null where id=p_user_key; end if;
 delete from public.checkin_sessions where expires_at<=now();
 insert into public.checkin_sessions(token_hash,user_id,expires_at) values(p_token_hash,p_user_key,now()+interval '24 hours');
 update public.checkin_settings set revision=revision+1 where singleton;
 select * into actor from public.checkin_accounts where id=p_user_key;
 return jsonb_build_object('id',actor.id,'name',actor.name,'role',actor.role,'group',actor.group_number);
end $$;
