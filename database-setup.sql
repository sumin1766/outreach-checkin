create table if not exists public.checkin_accounts (
 id text primary key check(length(id) between 1 and 200),
 name text not null check(length(btrim(name)) between 1 and 80),
 role text not null default 'pending' check(role in ('pending','leader','admin')),
 group_number smallint check(group_number between 1 and 10),
 created_at timestamptz not null default now(),
 check((role='leader' and group_number is not null) or (role<>'leader' and group_number is null))
);
create table if not exists public.checkin_sessions (
 token_hash text primary key check(token_hash ~ '^[a-f0-9]{64}$'),
 user_id text not null references public.checkin_accounts(id),
 expires_at timestamptz not null, created_at timestamptz not null default now()
);
create index if not exists checkin_session_expiry on public.checkin_sessions(expires_at);
create table if not exists public.checkin_members (
 id bigint generated by default as identity primary key check(id between 1 and 9007199254740991),
 name text not null check(length(btrim(name)) between 1 and 30),
 group_number smallint not null check(group_number between 1 and 10),
 active boolean not null default true, created_at timestamptz not null default now()
);
create index if not exists checkin_members_group on public.checkin_members(group_number,active);
create table if not exists public.checkin_attendance (
 member_id bigint not null references public.checkin_members(id),
 date date not null check(extract(dow from date) in (2,4,5)), checked boolean not null,
 updated_by text not null references public.checkin_accounts(id),
 updated_at timestamptz not null default now(), primary key(member_id,date)
);
create index if not exists checkin_attendance_date on public.checkin_attendance(date,member_id);
create table if not exists public.checkin_break_weeks (
 week date primary key check(extract(dow from week)=0),
 reason text not null check(length(btrim(reason)) between 1 and 80),
 updated_by text not null references public.checkin_accounts(id)
);
create table if not exists public.checkin_break_days (
 date date primary key check(extract(dow from date) in (2,4,5)),
 reason text not null check(length(btrim(reason)) between 1 and 80),
 updated_by text not null references public.checkin_accounts(id)
);
create table if not exists public.checkin_orders (
 user_id text primary key references public.checkin_accounts(id),member_ids bigint[] not null default '{}'
);
create table if not exists public.checkin_settings (
 singleton boolean primary key default true check(singleton),
 team_name text not null check(length(btrim(team_name)) between 1 and 40), revision bigint not null default 0
);
insert into public.checkin_settings(singleton,team_name) values(true,'우리 교회 전도팀') on conflict do nothing;
