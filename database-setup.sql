 plan_hash text not null check(plan_hash ~ '^[a-f0-9]{64}$'),revision bigint not null,
 expires_at timestamptz not null default now()+interval '10 minutes'
);
create index if not exists checkin_import_expiry on public.checkin_import_previews(expires_at);

