create or replace function public.checkin_command(p_session_hash text,p_action text,p_input jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare actor public.checkin_accounts; person public.checkin_members; target public.checkin_accounts;
 d date; w date; g int; v jsonb; ids bigint[]; expected bigint[]; reason text; inserted bigint; added bigint[]:='{}';
begin
 perform 1 from public.checkin_settings where singleton for update;
 actor:=public.checkin_actor(p_session_hash);
 if actor.role not in ('admin','leader') then raise exception using errcode='42501',message='승인이 필요합니다.'; end if;
 if jsonb_typeof(p_input) is distinct from 'object' then raise exception '잘못된 요청입니다.'; end if;
 if p_action='attendance' then
  d:=(p_input->>'date')::date;
  if d is null or extract(dow from d) not in (2,4,5) or d>(now() at time zone 'Asia/Seoul')::date or jsonb_typeof(p_input->'checked') is distinct from 'boolean' then raise exception '오늘까지의 화·목·금 출석만 기록할 수 있습니다.'; end if;
  select * into person from public.checkin_members where id=(p_input->>'memberId')::bigint and active;
  if not found or (actor.role<>'admin' and person.group_number<>actor.group_number) then raise exception using errcode='42501',message='배정된 조의 조원만 수정할 수 있습니다.'; end if;
  if exists(select 1 from public.checkin_break_days where date=d) or exists(select 1 from public.checkin_break_weeks where week=d-extract(dow from d)::int) then raise exception using errcode='P0001',message='출석을 쉬는 날입니다.'; end if;
  insert into public.checkin_attendance values(person.id,d,(p_input->>'checked')::boolean,actor.id,now()) on conflict(member_id,date) do update set checked=excluded.checked,updated_by=excluded.updated_by,updated_at=excluded.updated_at;
 elsif p_action='members:create' then
  if (p_input->>'group') is null or (p_input->>'group') !~ '^(10|[1-9])$' then raise exception '1~10조를 선택해주세요.'; end if;g:=(p_input->>'group')::int;
  if actor.role<>'admin' and g<>actor.group_number then raise exception using errcode='42501',message='배정된 조에만 등록할 수 있습니다.'; end if;
  if jsonb_typeof(p_input->'names') is distinct from 'array' or jsonb_array_length(p_input->'names') not between 1 and 100 then raise exception '1~100명의 이름을 입력해주세요.'; end if;
  for v in select value from jsonb_array_elements(p_input->'names') loop
   if jsonb_typeof(v)<>'string' or length(btrim(v#>>'{}')) not between 1 and 30 then raise exception '이름은 1~30자여야 합니다.'; end if;
   insert into public.checkin_members(name,group_number) values(btrim(v#>>'{}'),g) returning id into inserted;added:=array_append(added,inserted);
  end loop;
 elsif p_action='members:update' then
  select * into person from public.checkin_members where id=(p_input->>'id')::bigint;
  if not found or (actor.role<>'admin' and person.group_number<>actor.group_number) then raise exception using errcode='42501',message='배정된 조만 관리할 수 있습니다.'; end if;
  if jsonb_typeof(p_input->'active') is distinct from 'boolean' then raise exception '활동 상태를 확인해주세요.'; end if;
  update public.checkin_members set active=(p_input->>'active')::boolean where id=person.id;
 elsif p_action='order' then
  if jsonb_typeof(p_input->'memberIds') is distinct from 'array' then raise exception '전체 순서를 입력해주세요.'; end if;
  select coalesce(array_agg(value::bigint order by ordinality),'{}') into ids from jsonb_array_elements_text(p_input->'memberIds') with ordinality;
  select coalesce(array_agg(id order by id),'{}') into expected from public.checkin_members where active and (actor.role='admin' or group_number=actor.group_number);
  if (select coalesce(array_agg(id order by id),'{}') from unnest(ids) id)<>expected then raise exception '현재 관리하는 조원의 전체 순서를 중복 없이 지정해주세요.'; end if;
  insert into public.checkin_orders values(actor.id,ids) on conflict(user_id) do update set member_ids=excluded.member_ids;
 elsif p_action='users' then
  if actor.role<>'admin' then raise exception using errcode='42501',message='관리자만 계정을 배정할 수 있습니다.'; end if;
  select * into target from public.checkin_accounts where id=p_input->>'id';
  if not found or (p_input->>'role') is null or (p_input->>'role') not in ('pending','leader','admin') then raise exception '계정과 권한을 확인해주세요.'; end if;
  if target.id=actor.id and p_input->>'role'<>'admin' then raise exception '자신의 관리자 권한은 해제할 수 없습니다.'; end if;
  if p_input->>'role'='leader' then
   if (p_input->>'group') is null or (p_input->>'group') !~ '^(10|[1-9])$' then raise exception '조장에게 1~10조를 배정해주세요.'; end if;g:=(p_input->>'group')::int;
  else g:=null;if p_input->>'group' is not null then raise exception '조장 계정에만 조를 배정해주세요.'; end if;end if;
  update public.checkin_accounts set role=p_input->>'role',group_number=g where id=target.id;
 elsif p_action='settings' then
  if actor.role<>'admin' then raise exception using errcode='42501',message='관리자만 설정할 수 있습니다.'; end if;
  if jsonb_typeof(p_input->'teamName') is distinct from 'string' or length(btrim(p_input->>'teamName')) not between 1 and 40 then raise exception '팀 이름을 확인해주세요.'; end if;
  update public.checkin_settings set team_name=btrim(p_input->>'teamName') where singleton;
 elsif p_action in ('breaks:save','breaks:delete','break-days:save','break-days:delete') then
  if actor.role<>'admin' then raise exception using errcode='42501',message='관리자만 휴무를 설정할 수 있습니다.'; end if;
  if p_action like '%:save' then
   reason:=btrim(p_input->>'reason');if reason is null or length(reason) not between 1 and 80 then raise exception '휴무 사유를 확인해주세요.'; end if;
  end if;
  if p_action in ('breaks:save','breaks:delete') then
   w:=(p_input->>'week')::date;if w is null or extract(dow from w)<>0 then raise exception '출석 주간을 다시 선택해주세요.'; end if;
   if p_action='breaks:save' then insert into public.checkin_break_weeks values(w,reason,actor.id) on conflict(week) do update set reason=excluded.reason,updated_by=excluded.updated_by;
   else delete from public.checkin_break_weeks where week=w;if not found then raise exception '등록된 휴무를 찾을 수 없습니다.'; end if;end if;
  elsif p_action='break-days:save' then
   if jsonb_typeof(p_input->'dates') is distinct from 'array' or jsonb_array_length(p_input->'dates') not between 1 and 3 then raise exception '화·목·금 중 휴무일을 선택해주세요.'; end if;
   if exists(select 1 from jsonb_array_elements_text(p_input->'dates') x where extract(dow from x.value::date) not in (2,4,5)) or (select count(distinct value) from jsonb_array_elements_text(p_input->'dates'))<>jsonb_array_length(p_input->'dates') or (select count(distinct value::date-extract(dow from value::date)::int) from jsonb_array_elements_text(p_input->'dates'))<>1 then raise exception '같은 주의 화·목·금 중 휴무일을 선택해주세요.'; end if;
   for v in select value from jsonb_array_elements(p_input->'dates') loop
    d:=(v#>>'{}')::date;insert into public.checkin_break_days values(d,reason,actor.id) on conflict(date) do update set reason=excluded.reason,updated_by=excluded.updated_by;
   end loop;
  else d:=(p_input->>'date')::date;delete from public.checkin_break_days where date=d;if not found then raise exception '등록된 휴무일을 찾을 수 없습니다.'; end if;end if;
 else raise exception '지원하지 않는 작업입니다.';
 end if;
 update public.checkin_settings set revision=revision+1 where singleton;
 return jsonb_build_object('ok',true,'memberIds',to_jsonb(added));
end $$;

-- No browser role may create accounts, call RPCs, or bypass the application's session checks.
revoke all on function public.checkin_actor(text) from public,anon,authenticated,service_role;
do $$ declare f record; begin
 for f in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname in ('checkin_open_session','checkin_close_session','checkin_me','checkin_state','checkin_revision','checkin_command') loop
  execute format('revoke all on function %s from public,anon,authenticated',f.signature);
  execute format('grant execute on function %s to service_role',f.signature);
 end loop;
end $$;

create or replace function public.checkin_prepare_import(p_session_hash text,p_token_hash text,p_file_hash text,p_plan_hash text,p_revision bigint)
returns void language plpgsql security definer set search_path='' as $$
declare actor public.checkin_accounts; current_revision bigint;
begin
 select revision into current_revision from public.checkin_settings where singleton for update;
 actor:=public.checkin_actor(p_session_hash);
 if actor.role<>'admin' then raise exception using errcode='42501',message='관리자만 업로드할 수 있습니다.'; end if;
 if current_revision<>p_revision then raise exception using errcode='40001',message='데이터가 바뀌었습니다. 미리보기를 다시 확인해주세요.'; end if;
 delete from public.checkin_import_previews where expires_at<=now();
 if (select count(*) from public.checkin_import_previews where actor_id=actor.id)>=20 then raise exception '진행 중인 미리보기가 너무 많습니다. 잠시 후 다시 확인해주세요.'; end if;
 insert into public.checkin_import_previews(token_hash,actor_id,file_hash,plan_hash,revision) values(p_token_hash,actor.id,p_file_hash,p_plan_hash,p_revision);
end $$;
create or replace function public.checkin_commit_import(p_session_hash text,p_token_hash text,p_file_hash text,p_plan_hash text,p_members jsonb,p_attendance jsonb,p_overwrite boolean default false)
returns jsonb language plpgsql security definer set search_path='' as $$
declare actor public.checkin_accounts; receipt public.checkin_import_previews; current_revision bigint;
 v jsonb; inserted bigint; member_id_value bigint; member_map jsonb:='{}'; g int; d date; name_value text;
 added_members int:=0; added_records int:=0; changed_records int:=0; same_records int:=0; kept_records int:=0;
begin
 select revision into current_revision from public.checkin_settings where singleton for update;
 actor:=public.checkin_actor(p_session_hash);
 if actor.role<>'admin' then raise exception using errcode='42501',message='관리자만 업로드할 수 있습니다.'; end if;
 select * into receipt from public.checkin_import_previews where token_hash=p_token_hash and actor_id=actor.id and expires_at>now() for update;
 if not found or receipt.file_hash<>p_file_hash or receipt.plan_hash<>p_plan_hash or receipt.revision<>current_revision then raise exception using errcode='40001',message='미리보기가 만료되었거나 데이터가 바뀌었습니다. 다시 확인해주세요.'; end if;
 if jsonb_typeof(p_members) is distinct from 'array' or jsonb_typeof(p_attendance) is distinct from 'array' or jsonb_array_length(p_members)>20000 or jsonb_array_length(p_attendance)>20000 or p_overwrite is null then raise exception '업로드 내용을 확인해주세요.'; end if;
 if (select count(distinct value->>'key') from jsonb_array_elements(p_members))<>jsonb_array_length(p_members) then raise exception '신규 조원 키가 중복되었습니다.'; end if;
 for v in select value from jsonb_array_elements(p_members) loop
  if jsonb_typeof(v->'key') is distinct from 'string' or length(v->>'key') not between 1 and 200 or jsonb_typeof(v->'name') is distinct from 'string' or length(btrim(v->>'name')) not between 1 and 30 or coalesce(v->>'group','') !~ '^(10|[1-9])$' then raise exception '신규 명단 형식을 확인해주세요.'; end if;
  g:=(v->>'group')::int;name_value:=btrim(v->>'name');
  if exists(select 1 from public.checkin_members where name=name_value and group_number=g) then raise exception using errcode='40001',message='같은 이름의 조원이 이미 등록되어 있습니다. 다시 확인해주세요.'; end if;
  insert into public.checkin_members(name,group_number) values(name_value,g) returning id into inserted;
  member_map:=member_map||jsonb_build_object(v->>'key',inserted);added_members:=added_members+1;
 end loop;
 -- Resolve temporary member keys without trusting any client-generated database IDs.
 create temporary table checkin_import_rows(member_id bigint,date date,checked boolean,primary key(member_id,date)) on commit drop;
 for v in select value from jsonb_array_elements(p_attendance) loop
  if v->>'memberId' is not null and v->>'memberKey' is not null then raise exception '조원 ID와 신규 키를 동시에 지정할 수 없습니다.'; end if;
  member_id_value:=coalesce((v->>'memberId')::bigint,(member_map->>(v->>'memberKey'))::bigint);d:=(v->>'date')::date;
  if member_id_value is null or not exists(select 1 from public.checkin_members where id=member_id_value and active) or d is null or extract(dow from d) not in (2,4,5) or d>(now() at time zone 'Asia/Seoul')::date or jsonb_typeof(v->'checked') is distinct from 'boolean' then raise exception '조원 또는 출석 날짜·상태를 확인해주세요.'; end if;
  if exists(select 1 from public.checkin_break_days where date=d) or exists(select 1 from public.checkin_break_weeks where week=d-extract(dow from d)::int) then raise exception using errcode='40001',message='휴무가 변경되었습니다. 미리보기를 다시 확인해주세요.'; end if;
  insert into pg_temp.checkin_import_rows values(member_id_value,d,(v->>'checked')::boolean);
 end loop;
